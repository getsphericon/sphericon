// documentedVariable is one row of the configuration reference.
type documentedVariable struct {
	name string
	// production and development are the defaults of the production profile and of the
	// development and test ones; empty is no default.
	production, development string
	rules                   []string
	secret                  bool
	doc                     string
}

// outsideVariables are the variables a part of the program reads on its own, before or apart
// from Load, so the environment struct does not hold them.
var outsideVariables = []documentedVariable{
	{
		name: "SPHERICON_ENV",
		doc: "The profile the process runs under, read before anything else: it picks the `.env` files and the defaults " +
			"that depend on it. `development` (also when empty), `test` and `e2e` tolerate a missing `SPHERICON_JWT_SECRET` " +
			"and let a Workspace's SMTP Integration reach a private host; `development` and `test` log as text, and `e2e`, " +
			"the end-to-end suite's profile, has no rate limits. Any other name is a production profile. The release " +
			"image sets `production`.",
	},
	{
		name: "OTEL_CONFIG_FILE",
		doc: "Path of an OpenTelemetry declarative configuration file (YAML), which says where traces, metrics and " +
			"logs are exported. Unset, nothing is exported over OTLP.",
	},
}

// Reference is the configuration reference (docs/configuration.md, written by cmd/configdoc): every
// variable Load reads, in the order the environment struct declares it, with its default, its
// rules, whether it is a secret and its description, the doc comment of its field.
func Reference() ([]byte, error) {
	docs, err := fieldDocs()
	if err != nil {
		return nil, err
	}
	production, development := profileDefaults("production"), profileDefaults("development")
	vars, err := documentedFields(reflect.TypeFor[environment](), reflect.ValueOf(production), reflect.ValueOf(development), docs)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer
	b.WriteString(referenceIntro)
	b.WriteString("## Variables\n\n")
	writeTable(&b, vars)
	b.WriteString("\n## Variables read outside the configuration\n\n")
	writeTable(&b, outsideVariables)
	b.WriteString("\n## Secrets from files\n\n")
	b.WriteString("Docker and Kubernetes mount secrets as files. Each secret variable also accepts a `<NAME>_FILE` sibling ")
	b.WriteString("(`SPHERICON_JWT_SECRET_FILE=/run/secrets/jwt`) whose value is the path of a file read at start; the ")
	b.WriteString("trailing newline is trimmed. A value set directly wins and its file is never read; an unreadable or ")
	b.WriteString("empty file stops the start, naming the `_FILE` variable. `sphericon doctor` redacts every secret ")
	b.WriteString("value from what it prints. The secret variables:\n\n")
	for _, name := range secretVariables {
		fmt.Fprintf(&b, "- `%s`\n", name)
	}
	return b.Bytes(), nil
}

const referenceIntro = `---
title: "Configuration reference"
---

<!-- Code generated by cmd/configdoc from the config package; DO NOT EDIT. Run ` + "`mise run generate`" + `. -->

Every environment variable Sphericon reads, with its default and the rules its value must hold. A
value that breaks a rule stops the start with a message naming the variable.

The process environment wins over the ` + "`.env`" + ` files of a checkout, which are read in this order, a later
one overriding an earlier: ` + "`.env`, `.env.<SPHERICON_ENV>`, `.env.local`, `.env.<SPHERICON_ENV>.local`" + `
(the ` + "`test` and `e2e`" + ` profiles read only their own ` + "`.env.<SPHERICON_ENV>`" + `).

`

// writeTable writes vars as a Markdown table.
func writeTable(b *bytes.Buffer, vars []documentedVariable) {
	b.WriteString("| Variable | Default | Rules | Secret | Description |\n")
	b.WriteString("| --- | --- | --- | --- | --- |\n")
	for _, v := range vars {
		secret := ""
		if v.secret {
			secret = "yes"
		}
		rules := variableNames.ReplaceAllString(strings.Join(v.rules, "; "), "`$0`")
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n", v.name, defaultCell(v), cell(rules), secret, cell(v.doc))
	}
}

// variableNames match the variables a rule names (`must be below SPHERICON_…`), set as code.
var variableNames = regexp.MustCompile(`\b[A-Z][A-Z0-9]*(_[A-Z0-9]+)+\b`)

// defaultCell is the default of v, with the development one when the profiles differ.
func defaultCell(v documentedVariable) string {
	code := func(s string) string {
		if s == "" {
			return "—"
		}
		return "`" + cell(s) + "`"
	}
	if v.production == v.development {
		return code(v.production)
	}
	return code(v.production) + "; " + code(v.development) + " in development and test"
}

// cell is s on one line, its pipes escaped, so it fits a table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(s), " "), "|", `\|`)
}

// documentedFields are the variables of the struct type t, nested structs (the rate limits)
// included, with their defaults read from the production and development profiles' values.
func documentedFields(t reflect.Type, production, development reflect.Value, docs map[string]string) ([]documentedVariable, error) {
	var out []documentedVariable
	for i := range t.NumField() {
		f := t.Field(i)
		tag, ok := f.Tag.Lookup("env")
		if !ok {
			if f.Type.Kind() != reflect.Struct {
				return nil, fmt.Errorf("config: %s.%s has no env tag", t.Name(), f.Name)
			}
			nested, err := documentedFields(f.Type, production.Field(i), development.Field(i), docs)
			if err != nil {
				return nil, err
			}
			out = append(out, nested...)
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		doc := docs[t.Name()+"."+f.Name]
		if doc == "" {
			return nil, fmt.Errorf("config: %s (%s.%s) has no doc comment, which the configuration reference prints", name, t.Name(), f.Name)
		}
		v := documentedVariable{
			name:   name,
			rules:  rules(slices.Contains(strings.Split(opts, ","), "required"), f.Tag.Get("validate")),
			secret: slices.Contains(secretVariables, name),
			doc:    doc,
		}
		if d, ok := f.Tag.Lookup("envDefault"); ok {
			v.production, v.development = d, d
		} else {
			v.production, v.development = shown(production.Field(i)), shown(development.Field(i))
		}
		out = append(out, v)
	}
	return out, nil
}

// rules are what a value must be: set when the variable is required, then each validator tag.
func rules(required bool, validate string) []string {
	var out []string
	if required {
		out = append(out, "required")
	}
	for spec := range strings.SplitSeq(validate, ",") {
		tag, param, _ := strings.Cut(spec, "=")
		if tag == "" || tag == "omitnil" {
			continue
		}
		out = append(out, rule(tag, param))
	}
	return out
}

// shown is a profile's default as the variable would spell it, empty for none.
func shown(v reflect.Value) string {
	if d, ok := reflect.TypeAssert[time.Duration](v); ok {
		return d.String()
	}
	switch v.Kind() {
	case reflect.String:
		return v.String()
	case reflect.Bool:
		return strconv.FormatBool(v.Bool())
	case reflect.Int, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(v.Int(), 10)
	case reflect.Float64:
		return strconv.FormatFloat(v.Float(), 'g', -1, 64)
	case reflect.Pointer:
		if v.IsNil() {
			return ""
		}
		return shown(v.Elem())
	default:
		return fmt.Sprint(v.Interface())
	}
}

// fieldDocs are the doc comments of the config package's struct fields, keyed "Type.Field", read
// from its source next to this file.
func fieldDocs() (map[string]string, error) {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		return nil, errors.New("config: locate the package's source to read its doc comments")
	}
	files, err := filepath.Glob(filepath.Join(filepath.Dir(file), "*.go"))
	if err != nil {
		return nil, fmt.Errorf("config: list the package's source: %w", err)
	}
	docs := map[string]string{}
	fset := token.NewFileSet()
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		parsed, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("config: parse %s: %w", path, err)
		}
		ast.Inspect(parsed, func(n ast.Node) bool {
			spec, ok := n.(*ast.TypeSpec)
			if !ok {
				return true
			}
			if st, ok := spec.Type.(*ast.StructType); ok {
				for _, field := range st.Fields.List {
					for _, name := range field.Names {
						docs[spec.Name.Name+"."+name.Name] = field.Doc.Text()
					}
				}
			}
			return false
		})
	}
	return docs, nil
}
