-- +goose Up
-- Destructive (ADR 0033, ADR 0110): a User's Second factor is the second_factors table of its own
-- module, no longer columns of users. ent's diff wrote the table, its index and the column drops;
-- the copy of every factor (active, pending, or an enrollment identity a disable or a reset kept)
-- is written by hand between them, so no factor is lost. A factor enrolled before the enrollment
-- identity existed starts from 0, and its next enrollment takes 1.
-- create "second_factors" table
CREATE TABLE "second_factors" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, "secret_encrypted" character varying NULL, "generation" bigint NOT NULL, "confirmed_at" timestamptz NULL, "last_step" bigint NOT NULL DEFAULT 0, "user_id" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "second_factors_users_second_factor" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE CASCADE);
-- create index "second_factors_user_id_key" to table: "second_factors"
CREATE UNIQUE INDEX "second_factors_user_id_key" ON "second_factors" ("user_id");
-- copy every User's factor into it
INSERT INTO "second_factors" ("user_id", "secret_encrypted", "generation", "confirmed_at", "last_step")
SELECT "id", NULLIF("second_factor_secret_encrypted", ''), COALESCE("second_factor_generation", 0), "second_factor_confirmed_at", "second_factor_last_step"
FROM "users"
WHERE COALESCE("second_factor_secret_encrypted", '') <> '' OR "second_factor_generation" IS NOT NULL
ORDER BY "id";
-- modify "users" table
ALTER TABLE "users" DROP COLUMN "second_factor_secret_encrypted", DROP COLUMN "second_factor_confirmed_at", DROP COLUMN "second_factor_last_step", DROP COLUMN "second_factor_generation";

-- +goose Down
-- reverse: modify "users" table
ALTER TABLE "users" ADD COLUMN "second_factor_generation" bigint NULL, ADD COLUMN "second_factor_last_step" bigint NOT NULL DEFAULT 0, ADD COLUMN "second_factor_confirmed_at" timestamptz NULL, ADD COLUMN "second_factor_secret_encrypted" character varying NULL;
-- reverse: copy every User's factor back
UPDATE "users" SET "second_factor_secret_encrypted" = f."secret_encrypted", "second_factor_generation" = f."generation",
  "second_factor_confirmed_at" = f."confirmed_at", "second_factor_last_step" = f."last_step"
FROM "second_factors" f WHERE f."user_id" = "users"."id";
-- reverse: create index "second_factors_user_id_key" to table: "second_factors"
DROP INDEX "second_factors_user_id_key";
-- reverse: create "second_factors" table
DROP TABLE "second_factors";
