-- +goose Up
-- ADR 0124: every Step an Enrollment reaches leaves a Step record, and a wait holds the Enrollment
-- on itself. ent's diff wrote the table; the moves of the Enrollments and their jobs, and the
-- records of the Steps they stand on, are written by hand. The release is stopped for it: a
-- release before this one parks an Enrollment on the Step after a wait.
-- create "automation_step_records" table
CREATE TABLE "automation_step_records" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "created_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, "updated_at" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, "step_id" character varying NOT NULL, "reached_at" timestamptz NOT NULL, "left_at" timestamptz NULL, "outcome" character varying NULL, "skip_reason" character varying NULL, "due_at" timestamptz NULL, "run_id" bigint NOT NULL, "workspace_id" bigint NOT NULL, PRIMARY KEY ("id"), CONSTRAINT "automation_step_records_automation_runs_run" FOREIGN KEY ("workspace_id", "run_id") REFERENCES "automation_runs" ("workspace_id", "id") ON UPDATE NO ACTION ON DELETE CASCADE, CONSTRAINT "automation_step_records_workspaces_automation_step_records" FOREIGN KEY ("workspace_id") REFERENCES "workspaces" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION, CONSTRAINT "automation_step_records_left_check" CHECK ((left_at IS NULL) = (outcome IS NULL)), CONSTRAINT "automation_step_records_outcome_check" CHECK ((outcome)::text = ANY ((ARRAY['done'::character varying, 'skipped'::character varying])::text[])), CONSTRAINT "automation_step_records_reason_check" CHECK ((outcome IS NOT NULL) OR (skip_reason IS NULL)), CONSTRAINT "automation_step_records_skip_reason_check" CHECK ((skip_reason)::text = ANY ((ARRAY['suppressed'::character varying, 'unsubscribed_everything'::character varying, 'unsubscribed_source'::character varying, 'unconfirmed'::character varying, 'no_destination'::character varying, 'contact_erased'::character varying, 'no_local_time'::character varying, 'frequency_cap'::character varying])::text[])), CONSTRAINT "automation_step_records_skipped_check" CHECK ((((outcome)::text = 'done'::text) AND (skip_reason IS NULL)) OR (((outcome)::text = 'skipped'::text) AND (skip_reason IS NOT NULL))));
-- create index "automation_step_records_workspace_id_run_id_step_id" to table: "automation_step_records"
CREATE UNIQUE INDEX "automation_step_records_workspace_id_run_id_step_id" ON "automation_step_records" ("workspace_id", "run_id", "step_id");

-- An Enrollment parked on the Step after a wait (past the last Step when the wait was the last)
-- moves to the wait itself, keeping its resume moment, which is the wait's due moment now; the job
-- queued for that moment names the wait. A run step job is not unique by its args, so river's
-- unique key needs no new derivation.
WITH "targets" AS (
  SELECT r."id", COALESCE(r."current_step_id", '') AS "parked_on", w."step" ->> 'id' AS "wait_id"
  FROM "automation_runs" r
  JOIN "automation_versions" v ON v."id" = r."version_id"
  CROSS JOIN LATERAL (
    SELECT t."step"
    FROM jsonb_array_elements(v."steps" -> 'steps') WITH ORDINALITY AS t("step", "position")
    WHERE t."position" + 1 = CASE
      WHEN r."current_step_id" IS NULL THEN jsonb_array_length(v."steps" -> 'steps') + 1
      ELSE (
        SELECT c."position"
        FROM jsonb_array_elements(v."steps" -> 'steps') WITH ORDINALITY AS c("step", "position")
        WHERE c."step" ->> 'id' = r."current_step_id"
      )
    END
  ) AS w
  WHERE r."status" = 'active'
    AND r."resume_at" IS NOT NULL
    AND w."step" ->> 'type' = 'wait'
), "jobs" AS (
  UPDATE "river_job" j
  SET "args" = jsonb_set(j."args", '{step_id}', to_jsonb(t."wait_id"))
  FROM "targets" t
  WHERE j."kind" = 'automation_run_step'
    AND j."state" NOT IN ('completed', 'cancelled', 'discarded')
    AND (j."args" ->> 'run_id')::bigint = t."id"
    AND j."args" ->> 'step_id' = t."parked_on"
)
UPDATE "automation_runs" r
SET "current_step_id" = t."wait_id"
FROM "targets" t
WHERE r."id" = t."id";

-- An Enrollment still past the last Step completes now, as the move that left its last Step does
-- from this release on; the job queued to complete it finds it ended and does nothing.
UPDATE "automation_runs"
SET "status" = 'completed', "ended_at" = CURRENT_TIMESTAMP, "resume_at" = NULL
WHERE "status" = 'active' AND "current_step_id" IS NULL;

-- Each active Enrollment has the record of the Step it stands on, so the move that leaves it stamps
-- it: reached when its cursor last moved, and a wait due at its resume moment.
INSERT INTO "automation_step_records" ("workspace_id", "run_id", "step_id", "reached_at", "due_at", "created_at", "updated_at")
SELECT r."workspace_id", r."id", r."current_step_id", r."updated_at", r."resume_at", CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM "automation_runs" r
WHERE r."status" = 'active' AND r."current_step_id" IS NOT NULL;

-- +goose Down
-- An Enrollment on a wait whose due moment is set goes back to the Step after it, past the last
-- Step when the wait was the last, keeping the moment, and its queued job names that Step ("" past
-- the last). An Enrollment this migration completed stays completed.
WITH "targets" AS (
  SELECT r."id", r."current_step_id" AS "wait_id", (
    SELECT n."step" ->> 'id'
    FROM jsonb_array_elements(v."steps" -> 'steps') WITH ORDINALITY AS n("step", "position")
    WHERE n."position" = w."position" + 1
  ) AS "next_id"
  FROM "automation_runs" r
  JOIN "automation_versions" v ON v."id" = r."version_id"
  CROSS JOIN LATERAL (
    SELECT t."position"
    FROM jsonb_array_elements(v."steps" -> 'steps') WITH ORDINALITY AS t("step", "position")
    WHERE t."step" ->> 'id' = r."current_step_id" AND t."step" ->> 'type' = 'wait'
  ) AS w
  WHERE r."status" = 'active' AND r."resume_at" IS NOT NULL
), "jobs" AS (
  UPDATE "river_job" j
  SET "args" = jsonb_set(j."args", '{step_id}', to_jsonb(COALESCE(t."next_id", '')))
  FROM "targets" t
  WHERE j."kind" = 'automation_run_step'
    AND j."state" NOT IN ('completed', 'cancelled', 'discarded')
    AND (j."args" ->> 'run_id')::bigint = t."id"
    AND j."args" ->> 'step_id' = t."wait_id"
)
UPDATE "automation_runs" r
SET "current_step_id" = t."next_id"
FROM "targets" t
WHERE r."id" = t."id";
