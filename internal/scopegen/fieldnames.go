// FieldNames writes the json names of the contract's request fields into the kernel package
// fieldname: every property of every request body, nested ones included, and every parameter of
// every operation, across the documents. A refusal is reported under one of them
// (validation.RefuseField), and the app shows it under the field of that name, so a module names
// the field by its constant and a name the contract does not have fails to compile.
var FieldNames = fieldNames{
	Specs: []string{siteSpec, externalSpec, serviceSpec, "openapi/collect.openapi.json", "openapi/staff.openapi.json", "openapi/staffee.openapi.json"},
	Out:   "internal/kernel/fieldname/fieldnames_gen.go",
}

type fieldNames struct {
	Specs []string
	Out   string
}

// Write reads the documents and writes the file.
func (f fieldNames) Write() error {
	docs := map[string][]byte{}
	for _, spec := range f.Specs {
		raw, err := os.ReadFile(spec)
		if err != nil {
			return err
		}
		docs[spec] = raw
	}
	src, err := f.Generate(docs)
	if err != nil {
		return err
	}
	return os.WriteFile(f.Out, src, 0o600)
}

// Generate renders the file from the documents, by name.
func (f fieldNames) Generate(docs map[string][]byte) ([]byte, error) {
	names := map[string]bool{}
	for spec, raw := range docs {
		if err := requestFields(raw, names); err != nil {
			return nil, fmt.Errorf("scopegen: %s: %w", spec, err)
		}
	}
	byGo := map[string]string{}
	for name := range names {
		g := goName(name)
		if other, ok := byGo[g]; ok {
			return nil, fmt.Errorf("scopegen: request fields %q and %q are both %s in Go", other, name, g)
		}
		byGo[g] = name
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/scopegen from openapi/*.openapi.json. DO NOT EDIT.\n\npackage fieldname\n\n")
	b.WriteString("// The json names of the contract's request fields: the properties of the request bodies and the\n")
	b.WriteString("// parameters of the operations, which a refusal is reported under.\nconst (\n")
	for _, g := range slices.Sorted(maps.Keys(byGo)) {
		fmt.Fprintf(&b, "\t%s = %q\n", g, byGo[g])
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// requestFields adds to names the request fields of one document.
func requestFields(raw []byte, names map[string]bool) error {
	var doc struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Schemas map[string]schema `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		return err
	}
	seen := map[string]bool{}
	var walk func(s schema)
	walk = func(s schema) {
		if s.Ref != "" {
			name := s.Ref[strings.LastIndex(s.Ref, "/")+1:]
			if !seen[name] {
				seen[name] = true
				walk(doc.Components.Schemas[name])
			}
			return
		}
		for name, prop := range s.Properties {
			names[name] = true
			walk(prop)
		}
		for _, sub := range [][]schema{s.AllOf, s.AnyOf, s.OneOf} {
			for _, x := range sub {
				walk(x)
			}
		}
		if s.Items != nil {
			walk(*s.Items)
		}
		if s.AdditionalProperties != nil {
			walk(*s.AdditionalProperties)
		}
	}
	for _, item := range doc.Paths {
		for _, body := range item {
			var op struct {
				Parameters []struct {
					Name string `json:"name"`
				} `json:"parameters"`
				RequestBody struct {
					Content map[string]struct {
						Schema schema `json:"schema"`
					} `json:"content"`
				} `json:"requestBody"`
			}
			if err := json.Unmarshal(body, &op); err != nil {
				continue // a path-level member that is not an operation
			}
			for _, p := range op.Parameters {
				if p.Name != "" {
					names[p.Name] = true
				}
			}
			for _, c := range op.RequestBody.Content {
				walk(c.Schema)
			}
		}
	}
	return nil
}

// schema is the part of an OpenAPI schema the request fields are read from.
type schema struct {
	Ref                  string            `json:"$ref"`
	Properties           map[string]schema `json:"properties"`
	AllOf                []schema          `json:"allOf"`
	AnyOf                []schema          `json:"anyOf"`
	OneOf                []schema          `json:"oneOf"`
	Items                *schema           `json:"items"`
	AdditionalProperties *schema           `json:"additionalProperties"`
}

// UnmarshalJSON reads a schema, taking `additionalProperties: true` (no schema) as none.
func (s *schema) UnmarshalJSON(raw []byte) error {
	type plain schema
	var p plain
	if err := json.Unmarshal(raw, &p); err != nil {
		if bytes.Equal(bytes.TrimSpace(raw), []byte("true")) || bytes.Equal(bytes.TrimSpace(raw), []byte("false")) {
			return nil
		}
		return err
	}
	*s = schema(p)
	return nil
}

// wordBoundary splits a json name into its words: at an underscore, a dash or a dot, and before an
// upper-case letter that follows a lower-case one or a digit.
var wordBoundary = regexp.MustCompile(`[_.\-]+|([a-z0-9])([A-Z])`)

// initialisms are the words Go writes in capitals.
var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "url": "URL", "urls": "URLs", "uri": "URI", "uris": "URIs", "ip": "IP",
	"api": "API", "http": "HTTP", "html": "HTML", "json": "JSON", "dns": "DNS", "ttl": "TTL",
	"uuid": "UUID", "smtp": "SMTP", "dkim": "DKIM", "jwt": "JWT",
}

// goName is the Go name of a json field name: `redirect_uris` is `RedirectURIs`, `logoUrl` is
// `LogoURL`.
func goName(name string) string {
	spaced := wordBoundary.ReplaceAllString(name, "$1 $2")
	var b strings.Builder
	for word := range strings.FieldsSeq(spaced) {
		if up, ok := initialisms[strings.ToLower(word)]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return b.String()
}
