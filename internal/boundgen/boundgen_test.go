package boundgen_test

import (
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/getsphericon/sphericon/internal/boundgen"
)

var holdDoc = []byte(`{"components":{"schemas":{
 "HoldInput":{"type":"object","properties":{
  "reasonCode":{"type":"string","minLength":1,"maxLength":64,"pattern":"^[a-z0-9_]+$"},
  "headers":{"type":"array","maxItems":5}}},
 "RetentionDays":{"type":"integer","minimum":1,"maximum":3650}}}}`)

func TestGenerateWritesAConstantPerBoundOfAPropertyAndItsOwner(t *testing.T) {
	src, err := boundgen.Generate(map[string][]byte{"openapi/service.openapi.json": holdDoc}, []boundgen.Bound{{
		Name: "HoldReasonCode", Doc: "is the machine code of a Hold's reason.",
		Spec: "openapi/service.openapi.json", Schema: "HoldInput", Property: "reasonCode",
		Owners: []string{"Hold"},
	}})
	require.NoError(t, err)

	out := string(src)
	require.Contains(t, out, "// Code generated by cmd/boundgen. DO NOT EDIT.")
	require.Contains(t, out, "package bounds")
	require.Regexp(t, `HoldReasonCodeMinLength\s+= 1\n`, out)
	require.Regexp(t, `HoldReasonCodeMaxLength\s+= 64\n`, out)
	require.Regexp(t, "HoldReasonCodePattern\\s+= `\\^\\[a-z0-9_\\]\\+\\$`", out)
	require.Regexp(t, `"HoldReasonCodeMaxLength":\s+\{"Hold"\}`, out)
	require.Regexp(t, `"HoldReasonCodePattern":\s+\{"Hold"\}`, out)
}

func TestGenerateReadsTheRangeOfAScalarAndTheItemsOfAList(t *testing.T) {
	src, err := boundgen.Generate(map[string][]byte{"openapi/site.openapi.json": holdDoc}, []boundgen.Bound{
		{Name: "RetentionDays", Doc: "is how long an Audit log is kept.", Spec: "openapi/site.openapi.json",
			Schema: "RetentionDays", Owners: []string{"Workspace"}},
		{Name: "HTTPActionHeaders", Doc: "are the headers of an http Action.", Spec: "openapi/site.openapi.json",
			Schema: "HoldInput", Property: "headers", Owners: []string{"internal/domain/orchestration/rules"}},
	})
	require.NoError(t, err)

	out := string(src)
	require.Regexp(t, `RetentionDaysMin\s+= 1\n`, out)
	require.Regexp(t, `RetentionDaysMax\s+= 3650\n`, out)
	require.Regexp(t, `HTTPActionHeadersMaxItems\s+= 5\n`, out)
	require.Regexp(t, `"HTTPActionHeadersMaxItems":\s+\{"internal/domain/orchestration/rules"\}`, out)
}

func TestGenerateReadsTheRangeAndDefaultOfASharedParameter(t *testing.T) {
	src, err := boundgen.Generate(map[string][]byte{"openapi/site.openapi.json": []byte(`{"components":{"parameters":{
	 "PageQuery.pageSize":{"name":"pageSize","in":"query","schema":{"type":"integer","minimum":1,"maximum":100,"default":25}}}}}`)},
		[]boundgen.Bound{{Name: "PageSize", Spec: "openapi/site.openapi.json", Parameter: "PageQuery.pageSize",
			Owners: []string{"internal/kernel/pagination"}}})
	require.NoError(t, err)

	out := string(src)
	require.Regexp(t, `PageSizeMax\s+= 100\n`, out)
	require.Regexp(t, `PageSizeDefault\s+= 25\n`, out)
	require.Contains(t, out, "// From site parameter PageQuery.pageSize.")
}

func TestGenerateRefusesABoundTheContractDoesNotDeclare(t *testing.T) {
	_, err := boundgen.Generate(map[string][]byte{"openapi/site.openapi.json": holdDoc}, []boundgen.Bound{
		{Name: "Missing", Spec: "openapi/site.openapi.json", Schema: "HoldInput", Property: "message", Owners: []string{"Hold"}},
	})
	require.ErrorContains(t, err, "HoldInput.message")

	_, err = boundgen.Generate(map[string][]byte{"openapi/site.openapi.json": []byte(
		`{"components":{"schemas":{"Plain":{"type":"string"}}}}`)}, []boundgen.Bound{
		{Name: "Plain", Spec: "openapi/site.openapi.json", Schema: "Plain", Owners: []string{"Hold"}},
	})
	require.ErrorContains(t, err, "declares no bound")
}

func TestGenerateRefusesABoundWithoutAnOwner(t *testing.T) {
	_, err := boundgen.Generate(map[string][]byte{"openapi/site.openapi.json": holdDoc}, []boundgen.Bound{
		{Name: "RetentionDays", Spec: "openapi/site.openapi.json", Schema: "RetentionDays"},
	})
	require.ErrorContains(t, err, "RetentionDays names no owner")
}

func TestGenerateTSExportsOnlyTheBoundsATypeScriptPackageOwns(t *testing.T) {
	src, err := boundgen.GenerateTS(map[string][]byte{"openapi/site.openapi.json": holdDoc}, []boundgen.Bound{
		{Name: "RetentionDays", Spec: "openapi/site.openapi.json", Schema: "RetentionDays", Owners: []string{"Workspace"}},
		{Name: "HoldReasonCode", Spec: "openapi/site.openapi.json", Schema: "HoldInput", Property: "reasonCode",
			Owners: []string{"packages/tracker/src"}},
	}, "packages/tracker/src")
	require.NoError(t, err)

	out := string(src)
	require.Contains(t, out, "// Code generated by cmd/boundgen. DO NOT EDIT.")
	require.Contains(t, out, "export const HoldReasonCodeMaxLength = 64\n")
	require.Contains(t, out, `export const HoldReasonCodePattern = "^[a-z0-9_]+$"`)
	require.NotContains(t, out, "RetentionDays")
}

func TestEveryBoundOfTheListIsInTheContract(t *testing.T) {
	specs, err := boundgen.ReadSpecs("../..", boundgen.Bounds)
	require.NoError(t, err)

	_, err = boundgen.Generate(specs, boundgen.Bounds)
	require.NoError(t, err)
}
