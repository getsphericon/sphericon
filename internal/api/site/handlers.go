// WelcomeEnqueuer schedules the platform welcome email after a Sign-up. Same
// jobs enqueue seam (river prod, inline tests).
type WelcomeEnqueuer interface {
	EnqueueWelcome(ctx context.Context, email, name string) error
}

// SystemMailEnqueuer schedules the self-service account emails (password reset,
// email verification, email-change confirmation) through the platform system
// sender. Same jobs enqueue seam (river prod, inline tests). The token is minted
// by the handler; the job builds the link.
type SystemMailEnqueuer interface {
	// EnqueuePasswordReset queues the reset mail. With send false the job is queued
	// all the same but nothing is delivered, so forgot-password costs the same
	// for every address.
	EnqueuePasswordReset(ctx context.Context, email, token string, send bool) error
	EnqueueEmailVerification(ctx context.Context, email, token string, send bool) error
	EnqueueEmailChangeConfirm(ctx context.Context, email, token string, send bool) error
	// EnqueueAddressTakenNotice queues the tokenless notice to the owner of a Taken
	// address (ADR 0031). With send false the job is queued but its mail is dropped.
	EnqueueAddressTakenNotice(ctx context.Context, email string, send bool) error
	// EnqueueIdentityLinkedNotice queues the notice to the owner of an account that a Sign-in
	// provider was linked to silently (ADR 0048); token is its "this was not me" link.
	EnqueueIdentityLinkedNotice(ctx context.Context, email, provider, token string) error
	// EnqueueUserDeletedNotice queues the one mail that tells an address its User was deleted
	// (ADR 0050).
	EnqueueUserDeletedNotice(ctx context.Context, email string) error
	// EnqueueUserDeletionLink queues the one-time link that confirms a passwordless User's
	// deletion (ADR 0050). With send false the job is queued but its mail is dropped.
	EnqueueUserDeletionLink(ctx context.Context, email, token string, send bool) error
	// EnqueueMemberInvite sends the workspace invite email. It is best-effort:
	// the invite also returns a copy-link, so a missing/failed mailer (common on
	// self-hosted with no SMTP) must not fail the invite.
	EnqueueMemberInvite(ctx context.Context, email, inviteURL, workspaceName, inviterName string) error
	// EnqueueSecondFactorRequired emails the Workspace's Users without a Second
	// factor that its Two-factor requirement is now on, with their deadline (ADR 0020).
	EnqueueSecondFactorRequired(ctx context.Context, workspaceID int64) error
	// EnqueuePasskeyNotice queues the notice to the owner of an account that a Passkey was
	// added or removed (ADR 0052), so a change they did not make is noticed.
	EnqueuePasskeyNotice(ctx context.Context, email string, change jobs.PasskeyChange, name string) error
}

