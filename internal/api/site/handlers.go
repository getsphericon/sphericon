// AuditLog is the read seam of the Enterprise Audit log (ADR 0022), implemented by
// ee/audit. Core knows only this interface: without a license Licensed is false and
// the page answers 402.
type AuditLog interface {
	Licensed() bool
	// Entries returns up to limit entries matching the filter, newest first, preceding
	// the cursor entry id (0 = from the newest), and the next page's cursor (0 = last page).
	Entries(ctx context.Context, s *ent.Scoped, f events.AuditFilter, cursor int64, limit int) ([]*ent.AuditEntry, int64, error)
	// Export records the export as an Audit entry of the scope's actor, then returns the
	// function that writes the entries matching the filter, newest first, as CSV.
	Export(ctx context.Context, s *ent.Scoped, f events.AuditFilter) (func(w io.Writer) error, error)
	// RetentionLicensed reports whether the retention window may be set (ADR 0014).
	RetentionLicensed() bool
}

// Origins are the public origins besides the app's own that a Workspace resource names: where an
// AI agent connects (config.MCPOrigin) and where the tracker snippet loads from and posts to
// (config.TrackerOrigin). A new one is a field here, one line in the resource and one in the wiring.
type Origins struct {
	MCP     string
	Tracker string
}

// Deps is everything the /site handlers are built from. The domain modules are
// the shared singletons the composition root registers once, so /site and /api
// cannot diverge on how a module is constructed.
type Deps struct {
	Accounts *accounts.Accounts
	// Passwords hashes the password a User sets (sign-up, reset, a verified link's new one).
	Passwords *credentials.Hasher
	// Deletion is the Workspace deletion cycle (ADR 0043).
	Deletion *workspacedeletion.Module
	// Instance is the Instance state no Workspace owns (ADR 0032).
	Instance *instance.Module
	// Attempts counts failed logins and password-reset mails per account (ADR
	// 0025); login and forgot-password share it.
	Attempts       *accounts.Attempts
	OAuth          *oauthserver.Service
	Bus            *events.Bus
	Webhooks       *webhooks.Module
	Outbound       *outbound.Module
	Segments       *segments.Module
	EventLog       *eventlog.Module
	Contacts       *contacts.Module
	Erasure        *erasure.Module
	Tags           *tags.Module
	Templates      *templates.Module
	BrandKit       *brandkit.Module
	Automations    *automations.Module
	Rules          *rules.Module
	Broadcasts     *broadcasts.Module
	Welcome        WelcomeEnqueuer
	SysMail        SystemMailEnqueuer
	SendingDomains *sendingdomains.Module
	JoinDomains    *joindomains.Module
	Integrations   *integrations.Module
	// CapturedMessages is the store of what the Workspace's Test inbox kept.
	CapturedMessages *capturedmessages.Module
	Tokens           *authtoken.Signer
	Tracker          *tracking.Tracker
	AppURL           string
	Audit            AuditLog
	AbuseWatch       abusewatch.Watch
	// SupportEmail is where a suspended Workspace's owner appeals (SPHERICON_SUPPORT_EMAIL).
	SupportEmail string
	// Origins are the public origins a Workspace's pages point at besides the app's own.
	Origins   Origins
	Analytics *analytics.Module
	// Sessions issues the session cookie on login (ADR 0020). The composition
	// root (server.New) builds it from the instance secret and SPHERICON_SESSION_TTL.
	Sessions *auth.Sessions
	// SecondFactor enrolls and verifies a User's TOTP Second factor (ADR 0020).
	SecondFactor *secondfactor.Module
	// Passkeys registers a User's Passkeys (ADR 0052).
	Passkeys *secondfactor.Passkeys
	// Clock is the time the site session's expiry and a Two-factor requirement's
	// grace are checked against (ADR 0020); nil means time.Now. Tests inject one to
	// move past a session's lifetime or a grace period.
	Clock func() time.Time
	// AccountLink mints the Owner's Account link token; nil when the installation is
	// not configured for it, which leaves the operation answering 404.
	AccountLink *accountlink.Link
	// Holds reads a Workspace's standing: the same module, so the same license gate,
	// the send path applies (ADR 0009).
	Holds *holds.Holds
	// RequireEmailVerification is the email verification gate (ADR 0030): when false,
	// a Sign-up takes a password and yields a Verified User at once, and login
	// checks no verification.
	RequireEmailVerification bool
	// SignupSurvey is the Sign-up survey module (built with signupsurvey.Enabled).
	SignupSurvey *signupsurvey.Module
	// Signin is the Sign-in providers the Instance enabled (ADR 0048); none enabled when
	// no provider is configured.
	Signin *signin.Providers
}

func NewHandlers(d Deps) *Handlers {
	now := d.Clock
	if now == nil {
		now = time.Now
	}
	h := &Handlers{
		accounts: d.Accounts, passwords: d.Passwords, deletion: d.Deletion, attempts: d.Attempts, bus: d.Bus, webhooks: d.Webhooks, outbound: d.Outbound,
		segments: d.Segments, eventlog: d.EventLog, contacts: d.Contacts, erasure: d.Erasure, tags: d.Tags, templates: d.Templates, brandKit: d.BrandKit,
		automations: d.Automations, rules: d.Rules, broadcasts: d.Broadcasts, welcome: d.Welcome,
		sysmail: d.SysMail, sendingDomains: d.SendingDomains, joinDomains: d.JoinDomains, integrations: d.Integrations, captured: d.CapturedMessages, tokens: d.Tokens, tracker: d.Tracker, appURL: d.AppURL,
		oauth: d.OAuth, audit: d.Audit, abuseWatch: d.AbuseWatch, supportEmail: d.SupportEmail, origins: d.Origins, analytics: d.Analytics, sessions: d.Sessions, secondFactor: d.SecondFactor, passkeys: d.Passkeys, now: now, instance: d.Instance, accountLink: d.AccountLink, holds: d.Holds, requireVerification: d.RequireEmailVerification, signupSurvey: d.SignupSurvey,
		signin:     d.Signin,
		challenges: d.Tokens.WithClock(d.Clock),
	}
	h.login = h.newLogin()
	h.signup = h.newSignUp()
	return h
}

var _ siteapi.Handler = (*Handlers)(nil)

// actor is the signed-in User as the actor of an Audit entry (ADR 0022), with the
// display name snapshotted. A name that cannot be loaded is left empty: the entry is
// still worth recording.
func (h *Handlers) actor(ctx context.Context) events.Actor {
	a := auth.GetSiteAuth(ctx)
	if a == nil {
		return events.Actor{}
	}
	actor := events.Actor{Kind: events.ActorUser, ID: strconv.FormatInt(a.UserID, 10)}
	if u, err := h.accounts.User(ctx, a.UserID); err == nil {
		actor.Name = u.Name
	}
	return actor
}

// secondFactorRequiredError is secondfactor.ErrRequired as the problem the site
// answers it with. Returned as an error, it is rendered by the server's error
// handler, which reads it through its Problem method.
type secondFactorRequiredError struct{}

func (secondFactorRequiredError) Error() string { return secondfactor.ErrRequired.Error() }
func (secondFactorRequiredError) Unwrap() error { return secondfactor.ErrRequired }

// Problem is the 403 second_factor_required answer.
func (secondFactorRequiredError) Problem() (status int, code, detail string) {
	return http.StatusForbidden, string(siteapi.ProblemCodeSecondFactorRequired), i18n.T("errors.second_factor_required", nil)
}

// mailNotQueued logs a notice mail that could not be queued. The response never depends on it (a
// failure shown to the caller would tell whether an address has an account) and a lost mail is
// asked for again.
func mailNotQueued(ctx context.Context, mail string, err error) {
	slog.WarnContext(ctx, "mail not enqueued", "mail", mail, "error", err)
}
