// Package fixturegen builds the fixture catalog: named Go constants for the
// anchor rows of the committed YAML fixtures.
//
// A row opts in with a line comment on its first line:
//
//   - id: 1 # fixture: Acme
//
// The generator reads the raw fixture files (template expressions must be quoted
// so they parse as YAML) and emits constants only for annotated rows: <Name>ID
// plus one constant per catalogued column the row carries (see catalogColumns).
package fixturegen

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// annotation matches `# fixture: Name` in a line comment.
var annotation = regexp.MustCompile(`#\s*fixture:\s*([A-Za-z][A-Za-z0-9]*)\s*$`)

// catalogColumns lists the YAML columns that yield constants, with the
// constant-name suffix and whether the value is an integer (else a string).
var catalogColumns = []struct {
	column, suffix string
	integer        bool
}{
	{"id", "ID", true},
	{"slug", "Slug", false},
	{"email", "Email", false},
	{"prefix", "Prefix", false},
	{"collect_key", "CollectKey", false},
	{"ingest_key", "IngestKey", false},
	{"name", "Name", false},
	{"domain", "Domain", false},
	{"url", "URL", false},
	{"action", "Action", false},
	{"key", "Key", false},
	{"destination", "Destination", false},
}

type constant struct {
	name, value, source string
}

// Generate reads every *.yml in dir and returns the formatted catalog source.
func Generate(dir string) ([]byte, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.yml"))
	if err != nil {
		return nil, err
	}
	slices.Sort(files)

	var consts []constant
	seen := map[string]string{}
	for _, file := range files {
		raw, err := os.ReadFile(file)
		if err != nil {
			return nil, err
		}
		base := filepath.Base(file)
		rows, err := annotatedRows(raw)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", base, err)
		}
		for name, row := range rows {
			if prev, dup := seen[name]; dup {
				return nil, fmt.Errorf("duplicate fixture name %q in %s and %s", name, prev, base)
			}
			seen[name] = base
			consts = append(consts, rowConstants(name, base, row)...)
		}
		if orphans := orphanNames(raw, rows); len(orphans) > 0 {
			return nil, fmt.Errorf("%s: fixture annotation(s) match no row (put it on the row's first line): %s",
				base, strings.Join(orphans, ", "))
		}
	}
	slices.SortFunc(consts, func(a, b constant) int { return strings.Compare(a.name, b.name) })

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/fixturegen from fixtures/*.yml; DO NOT EDIT.\n\n")
	buf.WriteString("package fixtures\n\n")
	buf.WriteString("// Fixture catalog: named anchor rows. Annotate a row with `# fixture: Name` on its\n")
	buf.WriteString("// first line in fixtures/*.yml and run `mise run generate`.\n")
	buf.WriteString("const (\n")
	for _, c := range consts {
		fmt.Fprintf(&buf, "\t// %s is from fixtures/%s.\n\t%s = %s\n", c.name, c.source, c.name, c.value)
	}
	buf.WriteString(")\n")
	return format.Source(buf.Bytes())
}

// orphanNames lists annotations in raw that no row claimed.
func orphanNames(raw []byte, rows map[string]*yaml.Node) []string {
	var names []string
	for line := range strings.SplitSeq(string(raw), "\n") {
		if name, ok := annotationName(line); ok {
			if _, claimed := rows[name]; !claimed {
				names = append(names, name)
			}
		}
	}
	return names
}

// annotatedRows returns the annotated mapping nodes of one fixture file by name.
func annotatedRows(raw []byte) (map[string]*yaml.Node, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	rows := map[string]*yaml.Node{}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.SequenceNode {
		return rows, nil
	}
	for _, row := range doc.Content[0].Content {
		if row.Kind != yaml.MappingNode || len(row.Content) < 2 {
			continue
		}
		// yaml.v3 attaches `- id: 1 # x` to the first value, or to the key/mapping.
		for _, n := range []*yaml.Node{row.Content[1], row.Content[0], row} {
			if name, ok := annotationName(n.LineComment); ok {
				if _, dup := rows[name]; dup {
					return nil, fmt.Errorf("duplicate fixture name %q", name)
				}
				rows[name] = row
				break
			}
		}
	}
	return rows, nil
}

// credentialColumns maps a hash column to the constant-name suffix of the plaintext
// it was derived from. The plaintext is the literal argument of the hashing
// template call (see credentialCall); a column holding a static hash yields nothing.
var credentialColumns = []struct{ column, suffix string }{
	{"password_hash", "Password"},
	{"secret_hash", "Secret"},
	{"second_factor_secret_encrypted", "TotpSecret"},
	{"totp_secret_encrypted", "TotpSecret"},
	{"code_hash", "Code"},
}

// credentialCall matches a quoted-string hashing or sealing call:
// {{argonHash "plaintext"}}, {{encrypt "secret"}}, {{recoveryCodeHash "code"}}.
var credentialCall = regexp.MustCompile(`^\{\{\s*(?:argonHash|bcryptHash|encrypt|recoveryCodeHash)\s+("(?:[^"\\]|\\.)*")\s*\}\}$`)

// annotationName extracts the fixture name from a line or line comment.
func annotationName(text string) (string, bool) {
	m := annotation.FindStringSubmatch(text)
	if m == nil {
		return "", false
	}
	return m[1], true
}

// columnValue returns the scalar value of the named column in a row mapping.
func columnValue(row *yaml.Node, name string) (string, bool) {
	for i := 0; i+1 < len(row.Content); i += 2 {
		if row.Content[i].Value == name {
			return row.Content[i+1].Value, true
		}
	}
	return "", false
}

func rowConstants(name, source string, row *yaml.Node) []constant {
	source = strings.TrimSuffix(source, ".yml")
	var out []constant
	for _, col := range credentialColumns {
		raw, ok := columnValue(row, col.column)
		if !ok {
			continue
		}
		m := credentialCall.FindStringSubmatch(strings.TrimSpace(raw))
		if m == nil {
			continue
		}
		plain, err := strconv.Unquote(m[1])
		if err != nil {
			continue
		}
		out = append(out, constant{name: name + col.suffix, value: strconv.Quote(plain), source: source})
	}
	for _, col := range catalogColumns {
		v, ok := columnValue(row, col.column)
		if !ok {
			continue
		}
		if !col.integer {
			v = strconv.Quote(v)
		}
		out = append(out, constant{name: name + col.suffix, value: v, source: source})
	}
	return out
}

// Write generates the catalog from the fixtures in dir and writes it to out.
func Write(dir, out string) error {
	src, err := Generate(dir)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600)
}
