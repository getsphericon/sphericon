// Package idgen writes the message ids of the backend catalog (internal/i18n/ids_gen.go): one
// i18n.ID variable per message of locales/en.json, named after its key, so a call that names a
// message the catalog lacks does not compile.
package idgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
	"unicode"
)

// Write reads the catalog at catalogPath and writes the ids to outPath.
func Write(catalogPath, outPath string) error {
	raw, err := os.ReadFile(catalogPath)
	if err != nil {
		return fmt.Errorf("read the catalog: %w", err)
	}
	src, err := Generate(raw)
	if err != nil {
		return err
	}
	if err := os.WriteFile(outPath, src, 0o600); err != nil {
		return fmt.Errorf("write the ids: %w", err)
	}
	return nil
}

// Generate is the Go source of the ids of the catalog raw (a flat JSON object of key to text).
func Generate(raw []byte) ([]byte, error) {
	var catalog map[string]string
	if err := json.Unmarshal(raw, &catalog); err != nil {
		return nil, fmt.Errorf("parse the catalog: %w", err)
	}
	keys := make([]string, 0, len(catalog))
	names := map[string]string{}
	for key := range catalog {
		name := Name(key)
		if other, taken := names[name]; taken {
			return nil, fmt.Errorf("the keys %q and %q both name the id %s", other, key, name)
		}
		names[name] = key
		keys = append(keys, key)
	}
	slices.Sort(keys)

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/i18ngen from internal/i18n/locales/en.json; DO NOT EDIT.\n\n")
	b.WriteString("package i18n\n\n")
	b.WriteString("// The messages of the catalog, one id per key. Add a message to locales/en.json and run\n")
	b.WriteString("// `mise run generate`.\n")
	b.WriteString("var (\n")
	for _, key := range keys {
		fmt.Fprintf(&b, "\t%s = ID{key: %q}\n", Name(key), key)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// Name is the Go name of a catalog key: its words, split on dots and underscores, each with a
// capital letter ("email.password_reset.subject" is EmailPasswordResetSubject).
func Name(key string) string {
	var b strings.Builder
	for word := range strings.FieldsFuncSeq(key, func(r rune) bool { return r == '.' || r == '_' }) {
		runes := []rune(word)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}
