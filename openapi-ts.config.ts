import { defineConfig } from '@hey-api/openapi-ts'
import type { UserConfig } from '@hey-api/openapi-ts'

// The generated TS types declare optional props as `field?: T` and tsconfig enables
// exactOptionalPropertyTypes. Zod's `.optional()` / `.nullish()` output `field?: T | undefined`,
// so a parsed value would not be assignable to the SDK body type. zod 4 has `.exactOptional()`
// (output `field?: T`) but the generator does not emit it, so emit it for optional object
// properties here. Fields with a default keep the stock output (the default makes them required).

const header = ['// @ts-nocheck', '// This file is auto-generated by @hey-api/openapi-ts']

// The full client of a browser-facing surface: types, fetch client, SDK with zod request
// validation, react-query options, zod schemas and MSW handlers.
const surface = (name: 'site' | 'staff' | 'staffee'): UserConfig => ({
  input: `./openapi/${name}.openapi.json`,
  output: { header, importFileExtension: '.ts', path: `./src/generated/${name}` },
  plugins: [
    {
      enums: 'javascript',
      name: '@hey-api/typescript',
    },
    '@hey-api/client-fetch',
    'msw',
    {
      name: '@hey-api/sdk',
      validator: { request: 'zod' },
    },
    {
      name: '@tanstack/react-query',
      queryOptions: true,
      mutationOptions: true,
      // Every key carries its operation's tags (the resource, e.g. `Site Segments`), so a
      // mutation invalidates the queries of its own resource without listing them
      // (useResourceMutation, src/hooks/useResourceMutation.ts).
      queryKeys: { tags: true },
      mutationKeys: { tags: true },
    },
    {
      name: 'zod',
      '~resolvers': {
        // An EntityId is a decimal string on the wire (the contract's `format: int64` on a
        // string, so the Go server parses it) and a `string` in the generated types. The
        // stock output for int64 is a coerced bigint, which JSON cannot carry: keep the string.
        number: (ctx) =>
          ctx.schema.format === 'int64'
            ? ctx
                .$(ctx.plugin.imports.z)
                .attr('string')
                .call()
                .attr('regex')
                .call(ctx.$.regexp('^[0-9]+$'))
            : undefined,
        object: (ctx) =>
          ctx.nodes.base({
            ...ctx,
            applyModifiers: (result, opts) => {
              if (!opts.optional || result.meta.default !== undefined) {
                return ctx.applyModifiers(result, opts)
              }
              const { chain } = ctx.applyModifiers(result, { ...opts, optional: false })
              return { chain: ctx.$(ctx.plugin.imports.z).attr('exactOptional').call(chain) }
            },
          }),
      },
    },
  ],
})

// The external API client for Node servers: types, fetch client and SDK (no zod, no react-query).
const externalSdk: UserConfig = {
  input: './openapi/external.openapi.json',
  output: { header, importFileExtension: '.ts', path: './packages/node/src/generated/external' },
  plugins: [
    {
      enums: 'javascript',
      name: '@hey-api/typescript',
    },
    '@hey-api/client-fetch',
    '@hey-api/sdk',
  ],
}

export default defineConfig([
  externalSdk,
  surface('site'),
  surface('staff'),
  surface('staffee'),
  // The collect ingestion client of the tracker: types and SDK over ky, whose retry (backoff,
  // Retry-After) is how the tracker resends a refused batch.
  {
    input: './openapi/collect.openapi.json',
    output: {
      header,
      importFileExtension: '.ts',
      path: './packages/analytics/src/generated/collect',
    },
    plugins: [
      {
        enums: 'javascript',
        name: '@hey-api/typescript',
      },
      '@hey-api/client-ky',
      '@hey-api/sdk',
    ],
  },
])
