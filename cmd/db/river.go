package main

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/riverqueue/river/riverdriver"
	"github.com/riverqueue/river/riverdriver/riverpgxv5"
)

// riverMarker starts each river migration version inside a migration file, so the
// generator knows which versions the migrations/ directory already carries.
var riverMarker = regexp.MustCompile(`(?m)^-- river main migration (\d+)`)

// riverFirstLineVersion is the first version whose river_migration table has a `line`
// column (005 rebuilds it keyed on (line, version)).
const riverFirstLineVersion = 5

// generateRiverMigration writes the goose migration for the river migration versions the
// directory does not carry yet. River's SQL comes from the driver of the river version in
// go.mod, so it cannot drift from the library; `river_migration` rows are written by hand
// because river only records them when its own migrator applies a version, and rivermigrate
// (Validate, a later migrate) must find them.
func generateRiverMigration(dir string) error {
	have := map[int]bool{}
	files, err := filepath.Glob(filepath.Join(dir, "*.sql"))
	if err != nil {
		return err
	}
	for _, name := range files {
		data, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		for _, m := range riverMarker.FindAllStringSubmatch(string(data), -1) {
			v, _ := strconv.Atoi(m[1])
			have[v] = true
		}
	}

	// The driver's FS holds the line's files under migration/<line>.
	fsys, err := fs.Sub(riverpgxv5.New(nil).GetMigrationFS(riverdriver.MigrationLineMain), "migration/"+riverdriver.MigrationLineMain)
	if err != nil {
		return err
	}
	versions, err := riverVersions(fsys)
	if err != nil {
		return err
	}
	pending := slices.DeleteFunc(slices.Clone(versions), func(v int) bool { return have[v] })
	if len(pending) == 0 {
		fmt.Println("river: the migrations directory is up to date")
		return nil
	}

	// One file per version: river applies each version in a transaction of its own, and
	// some versions cannot share one (004 adds an enum value that 006 then uses).
	base := time.Now().UTC()
	for i, v := range pending {
		sqlUp, err := fs.ReadFile(fsys, riverFile(fsys, v, "up"))
		if err != nil {
			return err
		}
		sqlDown, err := fs.ReadFile(fsys, riverFile(fsys, v, "down"))
		if err != nil {
			return err
		}

		var out strings.Builder
		out.WriteString("-- +goose Up\n")
		out.WriteString("-- River's job-queue schema, generated by `mise run db:river-migration` from the river\n")
		out.WriteString("-- version in go.mod. river owns these tables; do not edit by hand.\n\n")
		fmt.Fprintf(&out, "-- river main migration %03d\n", v)
		out.WriteString(gooseStatements(riverSQL(string(sqlUp))))
		out.WriteString("\n-- river records its own migrations; record this one too, or a later river migrate re-runs it.\n")
		out.WriteString(riverRecord(v) + "\n")

		out.WriteString("\n-- +goose Down\n")
		out.WriteString(riverForget(v) + "\n\n")
		out.WriteString(gooseStatements(riverSQL(string(sqlDown))))

		name := filepath.Join(dir, fmt.Sprintf("%s_river_%03d.sql", base.Add(time.Duration(i)*time.Second).Format("20060102150405"), v))
		if err := os.WriteFile(name, []byte(out.String()), 0o644); err != nil {
			return err
		}
		fmt.Println("river: wrote", name)
	}
	fmt.Println("river: run `atlas migrate hash --env local` next")
	return nil
}

// riverSQL renders river's SQL the way its migrator does with no schema configured: the
// schema template becomes nothing, so the tables land in the search_path's first schema.
func riverSQL(sqlText string) string {
	return strings.ReplaceAll(sqlText, "/* TEMPLATE: schema */", "")
}

// riverRecord is the INSERT that records the version in river_migration, whose shape
// 005 changes from (version) to (line, version).
func riverRecord(version int) string {
	if version < riverFirstLineVersion {
		return fmt.Sprintf("INSERT INTO river_migration (version) VALUES (%d);", version)
	}
	return fmt.Sprintf("INSERT INTO river_migration (line, version) VALUES ('main', %d);", version)
}

// riverForget removes the version's row before its down SQL runs (version 001's down
// drops the table; 005's reshapes it).
func riverForget(version int) string {
	if version < riverFirstLineVersion {
		return fmt.Sprintf("DELETE FROM river_migration WHERE version = %d;", version)
	}
	return fmt.Sprintf("DELETE FROM river_migration WHERE line = 'main' AND version = %d;", version)
}

// riverVersions lists the migration versions the driver carries, ascending.
func riverVersions(fsys fs.FS) ([]int, error) {
	entries, err := fs.ReadDir(fsys, ".")
	if err != nil {
		return nil, err
	}
	var versions []int
	for _, e := range entries {
		name, ok := strings.CutSuffix(e.Name(), ".up.sql")
		if !ok {
			continue
		}
		v, err := strconv.Atoi(strings.SplitN(name, "_", 2)[0])
		if err != nil {
			return nil, fmt.Errorf("river migration %q: %w", e.Name(), err)
		}
		versions = append(versions, v)
	}
	slices.Sort(versions)
	return versions, nil
}

// riverFile is the name of the version's up or down file.
func riverFile(fsys fs.FS, version int, direction string) string {
	matches, _ := fs.Glob(fsys, fmt.Sprintf("%03d_*.%s.sql", version, direction))
	if len(matches) == 0 {
		return fmt.Sprintf("%03d.%s.sql", version, direction)
	}
	return matches[0]
}

// dollarQuote matches the opening of a dollar-quoted body ($$ or $tag$).
var dollarQuote = regexp.MustCompile(`\$[A-Za-z_]*\$`)

// gooseStatements returns the SQL with every statement that holds a dollar-quoted body
// wrapped in goose's StatementBegin/End: goose would otherwise split the body at its
// inner semicolons.
func gooseStatements(sqlText string) string {
	var out strings.Builder
	for _, stmt := range splitStatements(sqlText) {
		if dollarQuote.MatchString(stmt) {
			out.WriteString("-- +goose StatementBegin\n" + stmt + "\n-- +goose StatementEnd\n\n")
		} else {
			out.WriteString(stmt + "\n\n")
		}
	}
	return strings.TrimRight(out.String(), "\n") + "\n"
}

// splitStatements splits SQL at the semicolons that end a statement: not those inside
// a quoted string, a comment or a dollar-quoted body. Each statement keeps its
// terminating semicolon and the comments that precede it.
func splitStatements(sqlText string) []string {
	var (
		stmts []string
		cur   strings.Builder
		i     int
	)
	flush := func() {
		if s := strings.TrimSpace(cur.String()); s != "" && !commentOnly(s) {
			stmts = append(stmts, s)
		}
		cur.Reset()
	}
	for i < len(sqlText) {
		switch {
		case strings.HasPrefix(sqlText[i:], "--"):
			end := strings.IndexByte(sqlText[i:], '\n')
			if end < 0 {
				end = len(sqlText) - i
			}
			cur.WriteString(sqlText[i : i+end])
			i += end
		case sqlText[i] == '\'':
			j := i + 1
			for j < len(sqlText) {
				if sqlText[j] == '\'' {
					if j+1 < len(sqlText) && sqlText[j+1] == '\'' {
						j += 2
						continue
					}
					break
				}
				j++
			}
			cur.WriteString(sqlText[i:min(j+1, len(sqlText))])
			i = min(j+1, len(sqlText))
		case sqlText[i] == '$' && dollarQuote.FindStringIndex(sqlText[i:]) != nil && dollarQuote.FindStringIndex(sqlText[i:])[0] == 0:
			tag := dollarQuote.FindString(sqlText[i:])
			end := strings.Index(sqlText[i+len(tag):], tag)
			stop := len(sqlText)
			if end >= 0 {
				stop = i + len(tag) + end + len(tag)
			}
			cur.WriteString(sqlText[i:stop])
			i = stop
		case sqlText[i] == ';':
			cur.WriteByte(';')
			i++
			flush()
		default:
			cur.WriteByte(sqlText[i])
			i++
		}
	}
	flush()
	return stmts
}

// commentOnly reports whether the text holds nothing but comments and whitespace.
func commentOnly(s string) bool {
	for _, line := range strings.Split(s, "\n") {
		if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "--") {
			return false
		}
	}
	return true
}
